"""
twin.py - Virtual farm (simplified digital twin) in 3D with pydeck.
Function 7 of the document.

  - Terrain view : 3D relief (elevation tiles built from SRTM and other DEMs)
                   draped with satellite imagery, plus the field outline.
  - Zones view   : every 30 m Landsat pixel (or each virtual zone) is a 3D column;
                   colour and height show NDVI, surface temperature or the change
                   between two dates.
The 3D model is generated by TerraShift; it is not a physical twin provided by NASA.
"""

import numpy as np
import pandas as pd
import pydeck as pdk

from src.field import bbox, grid_zones

ESRI_IMAGERY = "https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}"
TERRAIN_TILES = "https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png"

# indicator: (column, label, unit, value range for colours, colour ramp)
INDICATORS = {
    "NDVI (vegetation)": ("ndvi", "NDVI", "", (0.0, 0.8),
                          [(166, 97, 26), (223, 194, 125), (166, 219, 160), (27, 120, 55)]),
    "Surface temperature": ("lst_c", "Surface temp", "°C", (20, 55),
                            [(43, 131, 186), (171, 221, 164), (253, 174, 97), (215, 25, 28)]),
    "Change in NDVI (B − A)": ("ndvi_change", "NDVI change", "", (-0.4, 0.4),
                               [(202, 0, 32), (244, 165, 130), (209, 229, 240), (5, 113, 176)]),
}


def colour(values, vmin, vmax, ramp):
    """Map values to RGB colours along a ramp of 4 colours."""
    t = np.clip((np.asarray(values, dtype=float) - vmin) / (vmax - vmin), 0, 1)
    t = np.nan_to_num(t, nan=0.5)
    pos = t * (len(ramp) - 1)
    i = np.minimum(pos.astype(int), len(ramp) - 2)
    f = (pos - i)[:, None]
    ramp = np.array(ramp, dtype=float)
    rgb = ramp[i] * (1 - f) + ramp[i + 1] * f
    return [[int(r), int(g), int(b), 220] for r, g, b in rgb]


def view_state(polygon, pitch=55, zoom=None):
    lon0, lat0, lon1, lat1 = bbox(polygon)
    span = max(lon1 - lon0, lat1 - lat0)
    if zoom is None:
        zoom = float(np.clip(np.log2(360 / max(span, 1e-4)) - 1.2, 10, 18))
    return pdk.ViewState(longitude=(lon0 + lon1) / 2, latitude=(lat0 + lat1) / 2,
                         zoom=zoom, pitch=pitch, bearing=-20)


def outline(polygon, z=0):
    return [[p[0], p[1], z] for p in polygon + polygon[:1]]


