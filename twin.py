def _tile_xy(lat, lon, z):
    n = 2 ** z
    x = (lon + 180) / 360 * n
    y = (1 - np.arcsinh(np.tan(np.radians(lat))) / np.pi) / 2 * n
    return x, y


def _elevation_sampler(z=14):
    """Return f(lat_array, lon_array) -> elevation (m) read from the free Terrarium tiles."""
    import io
    import requests
    from PIL import Image
    tiles = {}

    def tile(tx, ty):
        if (tx, ty) not in tiles:
            raw = requests.get(TERRAIN_TILES.format(z=z, x=tx, y=ty), timeout=30).content
            a = np.asarray(Image.open(io.BytesIO(raw)).convert("RGB"), dtype=float)
            tiles[(tx, ty)] = a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768
        return tiles[(tx, ty)]

    def sample(lat, lon):
        x, y = _tile_xy(np.asarray(lat), np.asarray(lon), z)
        out = np.empty(x.shape)
        for i, (xi, yi) in enumerate(zip(x.ravel(), y.ravel())):
            grid = tile(int(xi), int(yi))
            out.flat[i] = grid[min(int((yi % 1) * 256), 255), min(int((xi % 1) * 256), 255)]
        return out
    return sample


def _satellite_rgb(b, size=256):
    """Satellite picture of the box b = [lon0, lat0, lon1, lat1] as an RGB array (top row = north)."""
    import io
    import requests
    from PIL import Image
    url = ("https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/export?"
           f"bbox={b[0]},{b[1]},{b[2]},{b[3]}&bboxSR=4326&imageSR=4326&size={size},{size}&format=png&f=image")
    raw = requests.get(url, timeout=30).content
    return np.asarray(Image.open(io.BytesIO(raw)).convert("RGB"), dtype=float)


def terrain_deck(polygon, elevation_m=0, exaggeration=2.0, pitch=60, cells=64, margin=0.35):
    """3D relief around the field built from Terrarium elevation tiles (SRTM and other DEMs),
    coloured with the satellite picture. The field sits at height 0; hills rise from there.
    Built as plain 3D triangles so it shows the same in the app and in the saved report."""
    lon0, lat0, lon1, lat1 = bbox(polygon)
    dx, dy = (lon1 - lon0) * margin, (lat1 - lat0) * margin
    b = [lon0 - dx, lat0 - dy, lon1 + dx, lat1 + dy]
    lons = np.linspace(b[0], b[2], cells + 1)
    lats = np.linspace(b[1], b[3], cells + 1)
    LON, LAT = np.meshgrid(lons, lats)
    try:
        elev = _elevation_sampler()(LAT, LON)
    except Exception:
        elev = np.zeros_like(LAT)
    base = float(np.median(elev)) if not elevation_m else float(elevation_m)
    Z = (elev - base) * exaggeration
    try:
        img = _satellite_rgb(b)
        h, w = img.shape[:2]
    except Exception:
        img = None

    # simple light from the north-west, so slopes are readable
    gy, gx = np.gradient(elev)
    shade = np.clip(1 + (gx - gy) * 0.06, 0.75, 1.25)

    tris = []
    for i in range(cells):
        for j in range(cells):
            p = lambda a, c: [round(float(LON[a, c]), 6), round(float(LAT[a, c]), 6), round(float(Z[a, c]), 1)]
            if img is not None:
                r = min(int((1 - (i + 0.5) / cells) * h), h - 1)
                c = min(int((j + 0.5) / cells * w), w - 1)
                rgb = img[r, c]
            else:
                rgb = np.array([190, 175, 140])
            col = [int(v) for v in np.clip(rgb * shade[i, j], 0, 255)] + [255]
            tris.append({"polygon": [p(i, j), p(i, j + 1), p(i + 1, j + 1)], "color": col})
            tris.append({"polygon": [p(i, j), p(i + 1, j + 1), p(i + 1, j)], "color": col})

    surface = pdk.Layer("SolidPolygonLayer", data=tris, get_polygon="polygon", get_fill_color="color",
                        extruded=False, filled=True)
    inside = (LON >= lon0) & (LON <= lon1) & (LAT >= lat0) & (LAT <= lat1)
    top = float(Z[inside].max()) + 5 if inside.any() else 6
    field = pdk.Layer("PathLayer", data=[{"path": outline(polygon, top)}],
                      get_path="path", get_color=[255, 230, 0], width_min_pixels=3)
    return pdk.Deck(layers=[surface, field], initial_view_state=view_state(polygon, pitch=pitch, zoom=None),
                    map_provider=None, map_style=None)


