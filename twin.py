def satellite_underlay(polygon, margin=0.3):
    lon0, lat0, lon1, lat1 = bbox(polygon)
    dx, dy = (lon1 - lon0) * margin, (lat1 - lat0) * margin
    b = [lon0 - dx, lat0 - dy, lon1 + dx, lat1 + dy]
    url = ("https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/export?"
           f"bbox={b[0]},{b[1]},{b[2]},{b[3]}&bboxSR=4326&imageSR=4326&size=1024,1024&format=png&f=image")
    return pdk.Layer("BitmapLayer", image=url, bounds=b, opacity=0.9)


def zone_table(pixels, polygon, column, rows=3, cols=3):
    """Mean value of the pixels in each virtual zone."""
    out = []
    for z in grid_zones(polygon, rows, cols):
        x0, y0, x1, y1 = z["bounds"]
        inside = pixels[(pixels["lon"] >= x0) & (pixels["lon"] < x1)
                        & (pixels["lat"] >= y0) & (pixels["lat"] < y1)]
        if len(inside):
            out.append({"zone": z["zone"], "polygon": z["polygon"], "pixels": len(inside),
                        "value": float(inside[column].mean())})
    return pd.DataFrame(out)


def hex_cells(pixels, column, area_m2=900):
    """Resample the 30 m Landsat pixels onto touching hexagons of the same area.
    Each hexagon takes the value of the nearest Landsat pixel (no new data is made up)."""
    data = pixels.dropna(subset=[column]).reset_index(drop=True)
    if len(data) < 4:
        return data.copy(), None

    lat_c = float(data["lat"].mean())
    m_lat, m_lon = 111320.0, 111320.0 * np.cos(np.radians(lat_c))
    lon0, lat0 = float(data["lon"].min()), float(data["lat"].min())
    px = (data["lon"].to_numpy() - lon0) * m_lon            # pixel centres in metres
    py = (data["lat"].to_numpy() - lat0) * m_lat
    values = data[column].to_numpy()

    cell = 30.0                                             # bucket the pixels for a fast nearest search
    buckets = {}
    for i, (x, y) in enumerate(zip(px, py)):
        buckets.setdefault((int(x // cell), int(y // cell)), []).append(i)

    r = float(np.sqrt(area_m2 / (3 * np.sqrt(3) / 2)))     # hexagon radius (m), same area as a pixel
    dx, dy = np.sqrt(3) * r, 1.5 * r                       # pointy-top hexagon spacing (m)
    max_d2 = (0.75 * 30.0) ** 2                             # only where a Landsat pixel is close
    rows = []
    for j, y in enumerate(np.arange(0, py.max() + dy / 2, dy)):
        for x in np.arange(dx / 2 if j % 2 else 0, px.max() + dx / 2, dx):
            bx, by = int(x // cell), int(y // cell)
            best, best_d2 = None, max_d2
            for ox in (-1, 0, 1):
                for oy in (-1, 0, 1):
                    for i in buckets.get((bx + ox, by + oy), ()):
                        d2 = (px[i] - x) ** 2 + (py[i] - y) ** 2
                        if d2 < best_d2:
                            best, best_d2 = i, d2
            if best is not None:
                rows.append({"lon": lon0 + x / m_lon, "lat": lat0 + y / m_lat, column: values[best]})
    return pd.DataFrame(rows), r


def zones_deck(pixels, polygon, indicator, mode="pixels", height_scale=1.0):
    column, label, unit, (vmin, vmax), ramp = INDICATORS[indicator]
    layers = [satellite_underlay(polygon)]
    span = (vmax - vmin) or 1
    if mode == "pixels":
        data, r = hex_cells(pixels, column)
        data["height"] = (data[column] - vmin).clip(lower=0) / span * 150 * height_scale + 2
        data["color"] = colour(data[column], vmin, vmax, ramp)
        data["text"] = data[column].round(2).astype(str)
        # Honeycomb: six-sided columns that touch each other
        layers.append(pdk.Layer("ColumnLayer", data=data, get_position=["lon", "lat"],
                                get_elevation="height", get_fill_color="color", radius=r or 13,
                                disk_resolution=6, angle=90, coverage=0.97, extruded=True,
                                get_line_color=[60, 45, 20, 90], material={"ambient": 0.55, "diffuse": 0.6,
                                                                         "shininess": 20},
                                pickable=True, auto_highlight=True))
    else:
        data = zone_table(pixels, polygon, column)
        data["height"] = (data["value"] - vmin).clip(lower=0) / span * 150 * height_scale + 2
        data["color"] = colour(data["value"], vmin, vmax, ramp)
        data["text"] = data["zone"] + ": " + data["value"].round(2).astype(str)
        layers.append(pdk.Layer("PolygonLayer", data=data, get_polygon="polygon",
                                get_elevation="height", get_fill_color="color", extruded=True,
                                pickable=True, auto_highlight=True, get_line_color=[255, 255, 255]))
    layers.append(pdk.Layer("PathLayer", data=[{"path": outline(polygon, 1)}], get_path="path",
                            get_color=[255, 230, 0], width_min_pixels=2))
    tooltip = {"text": f"{label} {{text}} {unit}"}
    return pdk.Deck(layers=layers, initial_view_state=view_state(polygon),
                    map_provider=None, map_style=None, tooltip=tooltip)


def compare_periods(a, b):
    """Match pixels of two dates (same 30 m grid) and compute the NDVI change B − A."""
    a = a.assign(key=a["lon"].round(5).astype(str) + a["lat"].round(5).astype(str))
    b = b.assign(key=b["lon"].round(5).astype(str) + b["lat"].round(5).astype(str))
    m = a.merge(b[["key", "ndvi", "lst_c"]], on="key", suffixes=("_a", ""))
    m["ndvi_change"] = m["ndvi"] - m["ndvi_a"]
    return m.drop(columns="key")
